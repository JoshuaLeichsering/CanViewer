import {
  byteTerms,
  describeFrame,
  describeSignal,
  fitsPayload,
  muxCondition,
  num,
  oneLine,
  rawKind,
  type ByteTerm,
  type MuxCondition,
} from './layout';
import { signalIdentifiers } from './names';

/**
 * "Copy decode pseudo-code": the steps that turn a frame's payload into the
 * physical value of each signal, written with C's integer operators so that
 * it reads (and ports) like C, but kept language-neutral where C would need
 * casts. It decodes exactly as CanViewer does (`decodeFrame`), which the
 * tests check by running the generated text against the decoder for every
 * signal of the corpus.
 *
 * The grammar is small on purpose:
 *   // comment
 *   NAME_raw = <data[i], >>, <<, &, | and integers>
 *   if NAME_raw >= <2^(n-1)>: NAME_raw = NAME_raw - <2^n>      (sign)
 *   NAME = NAME_raw [* factor] [+ offset | - offset]          (or float32(…), float64(…))
 *   if <condition>:                                            (multiplexing, body indented)
 * where a condition joins `X_raw == v` and `lo <= X_raw <= hi` with `or`
 * and `and`.
 */
export function decodePseudoCode(db: DbcDatabase, message: DbcMessage, fileName: string): string {
  const signals = message.signals;
  const { names, raws } = pseudoCodeVariables(signals);
  const index = new Map(signals.map((s, i) => [s, i]));
  const nameOf = (s: DbcSignal) => names[index.get(s)!];
  const rawOf = (s: DbcSignal) => raws[index.get(s)!];

  const lastByte = message.dlc - 1;
  const lines: string[] = [];
  describeFrame(db, message).forEach((line, i) => lines.push(`// ${oneLine(i === 0 ? `${message.name}: ${line}` : line)}`));
  if (message.comment) for (const line of message.comment.split(/\r?\n/)) lines.push(`// ${oneLine(line)}`.trimEnd());
  lines.push(
    '//',
    `// Decode pseudo-code generated by CanViewer from ${oneLine(fileName)}.`,
    message.dlc > 0
      ? `// data[0] .. data[${lastByte}] are the payload bytes; bit 0 is the least significant bit of a byte.`
      : '// The payload is empty.',
    '// Shifts and masks work on unsigned integers wide enough for the signal.',
  );
  if (signals.some((s) => rawKind(s) === 'float32' || rawKind(s) === 'float64')) {
    lines.push('// float32(x) and float64(x) read the bits of x as an IEEE 754 single or double.');
  }

  // A switch is decoded before the signals that test it.
  const conditions = new Map(signals.map((s) => [s, muxCondition(message, s)]));
  const order: DbcSignal[] = [];
  const visit = (s: DbcSignal) => {
    if (order.includes(s)) return;
    const condition = conditions.get(s)!;
    if (condition.kind === 'when') for (const term of condition.terms) visit(term.switch);
    order.push(s);
  };
  signals.forEach(visit);

  for (const signal of order) {
    const name = nameOf(signal);
    const raw = rawOf(signal);
    const condition = conditions.get(signal)!;
    lines.push('', `// ${oneLine(`${name === signal.name ? name : `${name} ("${signal.name}")`}: ${describeSignal(message, signal, nameOf)}`)}`);
    const values = Object.entries(signal.values ?? {}).sort(([a], [b]) => Number(a) - Number(b));
    if (values.length > 0) lines.push(`// values: ${oneLine(values.map(([v, text]) => `${v} = "${text}"`).join(', '))}`);
    if (!fitsPayload(signal, message.dlc)) {
      lines.push(`// ${name} lies outside the ${message.dlc}-byte payload, so it is not decoded.`);
      continue;
    }
    if (condition.kind === 'never') {
      lines.push(`// ${name} is never decoded: ${condition.why}.`);
      continue;
    }
    const body = [`${raw} = ${rawExpression(byteTerms(signal))}`];
    const kind = rawKind(signal);
    if (kind === 'signed' && signal.length > 0) {
      const half = 1n << BigInt(signal.length - 1);
      body.push(`if ${raw} >= ${half}: ${raw} = ${raw} - ${half * 2n}`);
    }
    const value = kind === 'float32' || kind === 'float64' ? `${kind}(${raw})` : raw;
    body.push(`${name} = ${scaled(value, signal.factor, signal.offset)}`);
    if (condition.kind === 'when') {
      lines.push(`if ${conditionCode(condition, rawOf)}:`, ...body.map((line) => `    ${line}`));
    } else {
      lines.push(...body);
    }
  }
  return lines.join('\n') + '\n';
}

/**
 * The variables of the pseudo-code, per signal: `NAME` for the physical
 * value and `NAME_raw` for the raw one, all distinct, none of them a word the
 * pseudo-code itself uses.
 */
export function pseudoCodeVariables(signals: DbcSignal[]): { names: string[]; raws: string[] } {
  const names = signalIdentifiers(signals, new Set(['data', 'float32', 'float64', 'and', 'or', 'not', 'in']));
  const taken = new Set(names);
  const raws = names.map((name) => {
    let raw = `${name}_raw`;
    while (taken.has(raw)) raw += '_';
    taken.add(raw);
    return raw;
  });
  return { names, raws };
}

const hexMask = (width: number) => '0x' + ((1 << width) - 1).toString(16).toUpperCase().padStart(2, '0');

/** `data[0] | (data[1] << 8)`, `(data[5] >> 4) & 0x0F`, … */
export function rawExpression(terms: ByteTerm[]): string {
  if (terms.length === 0) return '0';
  return terms
    .map((t) => {
      let text = `data[${t.byte}]`;
      let compound = false;
      const wrap = () => (compound ? `(${text})` : text);
      if (t.shift > 0) {
        text = `${wrap()} >> ${t.shift}`;
        compound = true;
      }
      if (t.shift + t.width < 8) {
        text = `${wrap()} & ${hexMask(t.width)}`;
        compound = true;
      }
      if (t.at > 0) {
        text = `${wrap()} << ${t.at}`;
        compound = true;
      }
      return compound && terms.length > 1 ? `(${text})` : text;
    })
    .join(' | ');
}

/** `x * factor + offset`, leaving out a factor of 1 and an offset of 0. */
function scaled(value: string, factor: number, offset: number): string {
  let text = value;
  if (factor !== 1) text += ` * ${num(factor)}`;
  if (offset !== 0) text +=offset < 0 ? ` - ${num(-offset)}` : ` + ${num(offset)}`;
  return text;
}

function conditionCode(condition: Extract<MuxCondition, { kind: 'when' }>, rawOf: (s: DbcSignal) => string): string {
  const terms = condition.terms.map(({ switch: sw, ranges }) => {
    const raw = rawOf(sw);
    const tests = ranges.map(([lo, hi]) => (lo === hi ? `${raw} == ${num(lo)}` : `${num(lo)} <= ${raw} <= ${num(hi)}`));
    return tests.length > 1 && condition.terms.length > 1 ? `(${tests.join(' or ')})` : tests.join(' or ');
  });
  return terms.join(' and ');
}
