import type { DbcDatabase, DbcMessage, DbcSignal } from '../dbc/types';
import { hexId } from '../format';
import { describeFrame, describeSignal, fitsPayload, j1939Of, oneLine, rawKind } from './layout';
import { messageIdentifier, signalIdentifiers } from './names';

/**
 * "Copy as C struct": a self-contained C snippet for one message, with its
 * identifier, extended flag and payload length as macros, and a struct with
 * one member per signal that holds the signal's raw value. The member type is
 * the smallest <stdint.h> type that holds the raw value (float or double for
 * IEEE signals), and a comment above each member describes the signal.
 *
 * The snippet compiles on its own with `cc -std=c99 -pedantic -Wall -Wextra
 * -Werror` (the tests check this for every message of the corpus).
 */
export function cStruct(db: DbcDatabase, message: DbcMessage, fileName: string): string {
  const id = messageIdentifier(message);
  const prefix = id.toUpperCase();
  const macros: Array<[string, string]> = [
    [`${prefix}_ID`, `${hexId(message.id, message.isExtended)}u`],
    [`${prefix}_IS_EXTENDED`, message.isExtended ? '1' : '0'],
    [`${prefix}_LENGTH`, `${message.dlc}u`],
  ];
  const j1939 = j1939Of(db, message);
  if (j1939) macros.push([`${prefix}_PGN`, `${j1939.pgn}u`]);

  // A member named like one of the macros would be expanded by the preprocessor.
  const members = signalIdentifiers(message.signals, new Set(macros.map(([name]) => name)));
  const nameOf = (s: DbcSignal) => members[message.signals.indexOf(s)];

  const lines = ['/*'];
  describeFrame(db, message).forEach((line, i) => lines.push(` * ${comment(i === 0 ? `${message.name}: ${line}` : line)}`));
  if (message.comment) for (const line of message.comment.split(/\r?\n/)) lines.push(` * ${comment(line)}`.trimEnd());
  lines.push(
    ' *',
    ` * C struct generated by CanViewer from ${comment(fileName)}.`,
    ' * Each member holds the raw value of a signal; physical value = raw * factor + offset.',
    ' */',
    '#include <stdint.h>',
    '',
    ...macros.map(([name, value]) => `#define ${name} ${value}`),
    '',
  );

  if (message.signals.length === 0) {
    lines.push(`/* ${comment(message.name)} has no signals, so there is no struct. */`);
    return lines.join('\n') + '\n';
  }

  lines.push('typedef struct {');
  message.signals.forEach((signal, i) => {
    const { type, suffix, note } = memberType(signal);
    const named = members[i] === signal.name ? '' : `"${signal.name}": `;
    const outside = fitsPayload(signal, message.dlc) ? '' : `, outside the ${message.dlc}-byte payload`;
    lines.push(`    /* ${comment(named + describeSignal(message, signal, nameOf) + outside + note)} */`);
    if (signal.comment) lines.push(`    /* ${comment(oneLine(signal.comment))} */`);
    lines.push(`    ${type} ${members[i]}${suffix};`);
  });
  lines.push(`} ${id}_t;`);
  return lines.join('\n') + '\n';
}

/** The smallest type that holds the raw value as the decoder reads it. */
export function memberType(signal: Pick<DbcSignal, 'valueType' | 'length'>): {
  type: string;
  suffix: string;
  note: string;
} {
  const kind = rawKind(signal);
  if (kind === 'float32') return { type: 'float', suffix: '', note: '' };
  if (kind === 'float64') return { type: 'double', suffix: '', note: '' };
  const width = [8, 16, 32, 64].find((w) => signal.length <= w);
  if (width === undefined) {
    // No integer type is wide enough: keep the raw bits as bytes.
    const bytes = Math.ceil(signal.length / 8);
    return { type: 'uint8_t', suffix: `[${bytes}]`, note: `; raw bits as ${bytes} bytes, most significant first` };
  }
  return { type: `${kind === 'signed' ? '' : 'u'}int${width}_t`, suffix: '', note: '' };
}

/**
 * Text that is safe inside a C block comment: it cannot end the comment or
 * open a nested one (which -Wcomment reports), and a line cannot end in a
 * backslash or the ??/ trigraph, which would join it with the next.
 */
function comment(text: string): string {
  return oneLine(text)
    .replace(/\*\//g, '* /')
    .replace(/\/\*/g, '/ *')
    .replace(/(\\|\?\?\/)$/, '$1 .');
}
